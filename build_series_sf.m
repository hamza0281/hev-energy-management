function build_series_sf()
mdl = 'series_hev_sf';
if bdIsLoaded(mdl), close_system(mdl,0); end
new_system(mdl); open_system(mdl);

% ---- Wheel power input (recorded from vehicle_base) ----
add_block('simulink/Sources/From Workspace',[mdl '/Pw_src'], ...
    'VariableName','Pw_in','Position',[30 60 100 90]);

% ---- Plant: motor + generator + battery + fuel (MATLAB Function) ----
add_block('simulink/User-Defined Functions/MATLAB Function',[mdl '/Plant'], ...
    'Position',[330 40 450 160]);
rt = sfroot;
emc = rt.find('-isa','Stateflow.EMChart','Path',[mdl '/Plant']);
emc.Script = plant_code();
pause(1);

% ---- Thermostat Stateflow chart ----
add_block('sflib/Chart',[mdl '/Thermostat'],'Position',[150 170 280 240]);
ch = rt.find('-isa','Stateflow.Chart','Path',[mdl '/Thermostat']);
ch.ChartUpdate = 'DISCRETE'; ch.SampleTime = '0.1';
d = Stateflow.Data(ch); d.Name = 'SOC';     d.Scope = 'Input';
d = Stateflow.Data(ch); d.Name = 'engOn';   d.Scope = 'Output';
d = Stateflow.Data(ch); d.Name = 'SOClow';  d.Scope = 'Parameter';
d = Stateflow.Data(ch); d.Name = 'SOChigh'; d.Scope = 'Parameter';
sOff = Stateflow.State(ch); sOff.Position = [40 100 160 70];
sOff.LabelString = sprintf('Engine_OFF\nentry: engOn = 0;');
sOn  = Stateflow.State(ch); sOn.Position  = [320 100 160 70];
sOn.LabelString  = sprintf('Engine_ON\nentry: engOn = 1;');
t0 = Stateflow.Transition(ch); t0.Destination = sOff;
t0.DestinationOClock = 0; t0.SourceEndPoint = t0.DestinationEndPoint - [0 30];
t1 = Stateflow.Transition(ch); t1.Source = sOff; t1.Destination = sOn;
t1.LabelString = '[SOC < SOClow]';
t2 = Stateflow.Transition(ch); t2.Source = sOn; t2.Destination = sOff;
t2.LabelString = '[SOC > SOChigh]';

% ---- SOC and fuel integrators ----
add_block('simulink/Math Operations/Gain',[mdl '/SOCgain'], ...
    'Gain','-1/Qbat','Position',[510 60 560 90]);
add_block('simulink/Continuous/Integrator',[mdl '/SOCint'], ...
    'InitialCondition','SOC0','Position',[590 60 630 90]);
add_block('simulink/Continuous/Integrator',[mdl '/FuelInt'], ...
    'Position',[510 110 550 140]);

% ---- Logging ----
logs = {'soc','eng','fuel','Pbat'};
for i = 1:numel(logs)
    add_block('simulink/Sinks/To Workspace',[mdl '/log_' logs{i}], ...
        'VariableName',[logs{i} '_log'],'SaveFormat','Timeseries', ...
        'Position',[700 30+50*i 770 60+50*i]);
end

% ---- Wires ----
add_line(mdl,'Pw_src/1','Plant/1','autorouting','on');
add_line(mdl,'Thermostat/1','Plant/2','autorouting','on');
add_line(mdl,'SOCint/1','Plant/3','autorouting','on');
add_line(mdl,'SOCint/1','Thermostat/1','autorouting','on');
add_line(mdl,'Plant/1','SOCgain/1','autorouting','on');
add_line(mdl,'SOCgain/1','SOCint/1','autorouting','on');
add_line(mdl,'Plant/2','FuelInt/1','autorouting','on');
add_line(mdl,'Plant/3','log_Pbat/1','autorouting','on');
add_line(mdl,'SOCint/1','log_soc/1','autorouting','on');
add_line(mdl,'Thermostat/1','log_eng/1','autorouting','on');
add_line(mdl,'FuelInt/1','log_fuel/1','autorouting','on');

set_param(mdl,'SolverType','Fixed-step','Solver','ode3', ...
    'FixedStep','0.1','StopTime','tEnd');
save_system(mdl, fullfile('models',mdl));
disp('series_hev_sf built. Now run run_series_sf');
end

function s = plant_code()
s = [ ...
'function [Ibat, mdot, Pbat] = plant(Pw, engOn, SOC)' newline ...
'eta_m = 0.92; eta_g = 0.92; Paux = 500;' newline ...
'Pregen = 20e3; Pchg = 15e3; Pe_on = 20e3; Pe_max = 70e3;' newline ...
'LHV = 42.5e6; Rint = 0.15;' newline ...
'socTab = [0 0.2 0.4 0.6 0.8 1];' newline ...
'vocTab = [170 185 195 202 210 220];' newline ...
'loadFrac = [0 0.05 0.10 0.20 0.40 0.60 0.80 1.00];' newline ...
'eta_eng  = [0.05 0.14 0.20 0.27 0.33 0.34 0.33 0.31];' newline ...
'if Pw >= 0' newline ...
'    Pmot = Pw/eta_m;' newline ...
'else' newline ...
'    Pmot = max(Pw*eta_m, -Pregen);' newline ...
'end' newline ...
'Pbus = Pmot + Paux;' newline ...
'Peng = 0;' newline ...
'if engOn > 0.5, Peng = Pe_on; end' newline ...
'Pb = Pbus - Peng*eta_g;' newline ...
'Pb = max(Pb, -Pchg);' newline ...
'Voc = interp1(socTab, vocTab, min(max(SOC,0),1));' newline ...
'Pb = min(Pb, 0.99*Voc^2/(4*Rint));' newline ...
'Ibat = (Voc - sqrt(Voc^2 - 4*Rint*Pb))/(2*Rint);' newline ...
'Pbat = Pb;' newline ...
'mdot = 0;' newline ...
'if Peng > 0' newline ...
'    eta = interp1(loadFrac, eta_eng, Peng/Pe_max);' newline ...
'    mdot = Peng/(eta*LHV);' newline ...
'end' newline ...
'end' newline];
end